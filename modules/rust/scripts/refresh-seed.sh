#!/usr/bin/env bash
# Re-resolve every offline crate set against the real crates.io, and write the
# results back into the repository. Needs network, so it deliberately ignores the
# offline cargo config the environment installs.
#
# One lock per mode. Modes with a `[patch.crates-io]` table are resolved with it
# active, so what lands in their lock is the set of *registry* crates the patched
# tree needs -- which drifts ahead of what the published releases need.
#
# Modes with a vendor hash file get that refreshed too: `fetchCargoVendor` is a
# fixed-output derivation, so its hash has to move whenever the lock does.
#
# Patched modes are slow (10-15 minutes is normal). Almost all of that is
# fetching the crates.io sparse index, not resolving.
#
# GENERATED from offline-devshells' rust backend: the mode tables are a
# generated file, sourced below.
set -euo pipefail

prefix="@commandPrefix@"
shell_name="@shellName@"

# Any syntactically valid SRI hash that cannot be the real one; Nix reports the
# correct hash when this fails to match.
placeholder="sha256-AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA="

# Filled in by the sourced file: the mode names, in order, and per-mode tables.
modes=()
declare -A seeds=() lock_paths=() online_configs=() hash_paths=()
# shellcheck source=/dev/null  # a store path, generated from `rust.modes`
source "@modeTables@"

root="${1:-.}"
root="$(cd "$root" && pwd)"

if ! command -v nix >/dev/null; then
    echo "$prefix-refresh-seed: needs \`nix\` on PATH to re-learn vendor hashes" >&2
    exit 1
fi

# Scratch directories, removed however the script exits.
scratch=()
cleanup() {
    if [ "${#scratch[@]}" -gt 0 ]; then
        rm -rf "${scratch[@]}"
    fi
}
trap cleanup EXIT

# Where a lock for this environment should live does not exist here. The usual
# cause is an environment defined by *another* flake -- offline-devshells' own
# embassy preset, say -- whose locks live in that flake, not in this one.
not_here() {
    cat >&2 <<EOF
$prefix-refresh-seed: '$1' does not exist under $root.

Either run this from the root of the repository that holds the locks (or pass
that root as the first argument), or -- if \`$shell_name\` comes from another
flake, such as offline-devshells' embassy preset -- its locks belong to that
flake and cannot be rewritten from here. Point the modes at files in your own
repository first (for the embassy preset: \`embassyPreset.locksDir = ./locks;\`
after copying its locks there), then run this again.
EOF
    exit 1
}

updated=()

for mode in "${modes[@]}"; do
    lock_path="${lock_paths[$mode]}"
    echo "==> $mode -> $lock_path"

    [ -d "$(dirname "$root/$lock_path")" ] || not_here "$(dirname "$lock_path")"

    # The seed workspace lives in the store and is read-only, so resolve in a
    # copy. The existing lock is seeded in first, so resolution keeps the pins it
    # can and this stays an update rather than a from-scratch re-resolve.
    work="$(mktemp -d)"
    scratch+=("$work")
    cp -r --no-preserve=mode "${seeds[$mode]}"/. "$work/"
    if [ -f "$root/$lock_path" ]; then
        install -m 0644 "$root/$lock_path" "$work/Cargo.lock"
    fi

    home="$(mktemp -d)"
    scratch+=("$home")
    install -m 0644 "${online_configs[$mode]}" "$home/config.toml"

    CARGO_HOME="$home" cargo generate-lockfile --manifest-path "$work/Cargo.toml"

    install -m 0644 "$work/Cargo.lock" "$root/$lock_path"
    updated+=("$lock_path")
done

default_header="# Fixed-output hash for a vendored crate set. GENERATED by $prefix-refresh-seed,
# which rewrites it whenever it re-resolves the lock."

for mode in "${modes[@]}"; do
    hash_path="${hash_paths[$mode]}"
    [ -n "$hash_path" ] || continue

    echo "==> $mode vendor hash -> $hash_path"
    hash_file="$root/$hash_path"
    [ -d "$(dirname "$hash_file")" ] || not_here "$(dirname "$hash_path")"

    # Everything but the quoted SRI string on its own line is the file's header
    # comment, and is preserved verbatim.
    if [ -f "$hash_file" ]; then
        header="$(sed '/^"/d' "$hash_file")"
        previous="$(sed -n 's/^"\(.*\)"$/\1/p' "$hash_file")"
    else
        header="$default_header"
        previous=""
    fi

    restore() {
        if [ -n "$previous" ]; then
            printf '%s\n"%s"\n' "$header" "$previous" >"$hash_file"
        else
            rm -f "$hash_file"
        fi
    }

    # Learn the real hash the only way Nix offers: write a hash that cannot be
    # right, build, and read back the one it reports. The build is *expected*
    # to fail, so its status is deliberately ignored -- under `pipefail` a
    # failing build inside the substitution would otherwise abort the script
    # right here, with the placeholder still in the file.
    printf '%s\n"%s"\n' "$header" "$placeholder" >"$hash_file"
    output="$(nix build --no-link "$root#$shell_name-vendor-$mode" 2>&1)" || true
    # First match only, and no `| head`: an early-closing reader can SIGPIPE
    # the writer, which `pipefail` would again turn into an abort.
    got="$(sed -n '/^ *got: */{s///p;q}' <<<"$output")"

    if [ -z "$got" ]; then
        # No mismatch reported means the build failed for some other reason.
        # Do not leave the placeholder behind, and show why.
        restore
        printf '%s\n' "$output" >&2
        echo >&2
        echo "$prefix-refresh-seed: could not determine the vendor hash for '$mode'" >&2
        echo "  (build output above). $hash_path is unchanged." >&2
        exit 1
    fi

    printf '%s\n"%s"\n' "$header" "$got" >"$hash_file"
    updated+=("$hash_path")
done

{
    echo
    echo "updated, under $root:"
    printf '  %s\n' "${updated[@]}"
    echo
    echo "now run: nix build"
} >&2
